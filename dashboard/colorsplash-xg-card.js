  // Format wait_ms as a human-friendly seconds string for the
  // timing input — always shown as "9.04 s" rather than "9040 ms"
  // (per #56 sub-2). Internal storage stays in milliseconds; the
  // input field reformats on render.
  _formatWaitMs(ms) {
    return (ms / 1000).toFixed(2);
  }
  _parseWaitInput(raw) {
    const v = parseFloat(raw);
    if (!Number.isFinite(v)) return 0;
    return Math.max(0, Math.round(v * 1000));
  }

  // Resolve LUT samples + active range for a given show byte.
  // Returns {samples, loopMs, activeStart, activeEnd}. The active
  // range crops the post-byte blackout from the timeline — and
  // because the blackout duration varies per show (Nova holds
  // ~5.5 s, Tidal Wave / Patriot Dream / etc. only ~2.5 s), we
  // trim by RGB brightness rather than a fixed millisecond
  // floor. Any leading sample whose max(r,g,b) is below
  // LIT_THRESHOLD is treated as part of the AC-interrupt
  // blackout and dropped from the active range.
  //
  // samples is the LIT portion only (passed to _timelineGradient
  // so the strip never renders the dark ramp-in). activeStart /
  // activeEnd are the t_ms bounds of that lit portion — used by
  // the marker + click handler.
  _showLutFor(byte) {
    const all = SHOW_LUT_DATA.filter((row) => row[0] === byte);
    let loopMs = SHOW_LOOPS_MS[byte] | 0;
    if (loopMs <= 0) loopMs = 30000;
    const LIT_THRESHOLD = 20;  // RGB channel max above blackout floor
    let firstLitIdx = 0;
    while (firstLitIdx < all.length) {
      const [, , r, g, b] = all[firstLitIdx];
      if (Math.max(r, g, b) > LIT_THRESHOLD) break;
      firstLitIdx++;
    }
    const samples = (firstLitIdx < all.length)
        ? all.slice(firstLitIdx)
        : all;  // all-dark fallback — keep full set so strip renders
    const activeStart = samples.length ? samples[0][1] : 0;
    // Strip spans exactly ONE LOOP starting from the first lit
    // moment, so the user sees a complete cycle. The captured
    // samples may not reach activeStart + loopMs (LUT decimation
    // clips at skip_ms + loop_ms, and step-detection only
    // captures hold midpoints) — the timeline-gradient renderer
    // extends the last sample's color out to the right edge.
    const activeEnd = activeStart + loopMs;
    return {samples, loopMs, activeStart, activeEnd};
  }

  // Map a wait_ms value into a percentage along the timeline strip,
  // accounting for the cropped blackout. Clamped to [0, 100] so a
  // wait_ms outside the active range still parks the marker at
  // a strip edge instead of overflowing.
  _waitMsToStripPct(t, activeStart, activeEnd) {
    const span = activeEnd - activeStart;
    if (span <= 0) return 0;
    return Math.max(0, Math.min(100,
        ((t - activeStart) / span) * 100));
  }

  // Inverse of _waitMsToStripPct — converts a click x percentage
  // along the strip back to a wait_ms value within the active
  // range. Used by the timeline tap handler.
  _stripPctToWaitMs(pct, activeStart, activeEnd) {
    const span = activeEnd - activeStart;
    return Math.round(activeStart + (pct / 100) * span);
  }

  // Build a CSS linear-gradient for the timeline strip. For
  // shows in DISCRETE_BAND_BYTES (Nova), each sample becomes a
  // hard-edged band centered on its t_ms; the band edges land on
  // the midpoints between consecutive samples. For all other
  // shows the colors blend smoothly between samples.
  _timelineGradient(byte, samples, activeStart, activeEnd) {
    if (!samples.length) {
      return "var(--secondary-background-color, #2c2c2e)";
    }
    const span = activeEnd - activeStart;
    if (span <= 0) {
      // Single-sample show — flat color across the strip.
      const [, , r, g, b] = samples[0];
      return `rgb(${r},${g},${b})`;
    }
    const tToPct = (t) => Math.max(0, Math.min(100,
        ((t - activeStart) / span) * 100));

    // Loop-closure: where the captured samples don't reach the
    // right edge of the loop period (LUT decimation cuts at
    // skip_ms+loop_ms, so we're typically missing the few
    // seconds of the show that play before the post-AC-blackout
    // first-lit moment), interpolate / band the tail back to the
    // FIRST sample's color. The cycle visibly closes — left edge
    // and right edge match — which both suggests the loop
    // structure and gives the user a hint of what's happening
    // through the data gap. Until the recapture (#55) lands more
    // complete data, this is the best signal we can offer.
    const first = samples[0];

    if (DISCRETE_BAND_BYTES.has(byte)) {
      // Hard-edged bands — one per sample, edges at midpoints.
      const stops = [];
      const lastIdx = samples.length - 1;
      for (let i = 0; i < samples.length; i++) {
        const t = samples[i][1];
        const r = samples[i][2], g = samples[i][3],
              b = samples[i][4];
        const left_t = (i === 0)
            ? activeStart
            : (samples[i - 1][1] + t) / 2;
        const right_t = (i === lastIdx)
            ? t  // stop AT the last sample's t_ms; tail band follows
            : (t + samples[i + 1][1]) / 2;
        const leftPct = tToPct(left_t).toFixed(2);
        const rightPct = tToPct(right_t).toFixed(2);
        stops.push(`rgb(${r},${g},${b}) ${leftPct}%`);
        stops.push(`rgb(${r},${g},${b}) ${rightPct}%`);
      }
      // Loop-closure band: from the last sample's t_ms out to
      // 100%, painted with the FIRST sample's color so the strip
      // visually wraps to the start of the cycle.
      if (samples.length) {
        const lastT = samples[lastIdx][1];
        const closeStartPct = tToPct(lastT).toFixed(2);
        stops.push(
            `rgb(${first[2]},${first[3]},${first[4]}) ${closeStartPct}%`);
        stops.push(
            `rgb(${first[2]},${first[3]},${first[4]}) 100%`);
      }
      return `linear-gradient(to right, ${stops.join(", ")})`;
    }

    // Smooth-blend default: one stop per sample at its t_ms pct.
    // Add a closing stop at 100% with the FIRST sample's color so
    // the gradient interpolates the tail back into the cycle's
    // starting color — visually closes the loop.
    const stops = samples.map(([_byte, t, r, g, b]) => {
      const pct = tToPct(t).toFixed(2);
      return `rgb(${r},${g},${b}) ${pct}%`;
    });
    const last = samples[samples.length - 1];
    const lastPct = tToPct(last[1]);
    if (lastPct < 99.5) {
      stops.push(`rgb(${first[2]},${first[3]},${first[4]}) 100%`);
    }
    return `linear-gradient(to right, ${stops.join(", ")})`;
  }

